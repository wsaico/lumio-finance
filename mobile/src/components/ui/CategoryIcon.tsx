export const PICKABLE_ICON_NAMES = Object.keys(ICON_MAP);

export function CategoryIcon({
  name,
  size = 20,
  color = '#FFFFFF',
  strokeWidth = 2.1,
}: {
  name?: string | null;
  size?: number;
  color?: string;
  strokeWidth?: number;
}) {
  const Icon = (name && ICON_MAP[name]) || CircleHelp;
  return <Icon size={size} color={color} strokeWidth={strokeWidth} />;
}
